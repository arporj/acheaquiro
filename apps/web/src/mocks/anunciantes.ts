/** Par de antes e depois dentro da galeria; a legenda fica na foto "antes". */
function par(parId: string, antes: string, depois: string, legenda: string): Foto[] {
  return [
    { ...foto(antes, legenda), parId, papelNoPar: "antes" },
    { ...foto(depois), parId, papelNoPar: "depois" },
  ];
}

function horario(porDia: Partial<Record<DiaSemana, IntervaloHorario[]>>): HorarioDia[] {
  return ([0, 1, 2, 3, 4, 5, 6] as DiaSemana[]).map((dia) => ({ dia, intervalos: porDia[dia] ?? [] }));
}

